export const getBlogBySlug = (slug) => {
  if (!slug) return null;
  const decoded = decodeURIComponent(String(slug)).replace(/\/+$/, "").trim().toLowerCase();
  return (
    blogsData.find(
      (b) =>
        b.slug.toLowerCase() === decoded ||
        (b.aliases &&
          Array.isArray(b.aliases) &&
          b.aliases.some((alias) => alias.toLowerCase() === decoded))
    ) || null
  );
};

